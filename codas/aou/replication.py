"""A replication package per outcome: what an independent cohort needs to test the same hypotheses the same way.

Definitions and plans only, never participant data: the cohort spec and the SQL that extracts it (code; the
CDR named by placeholder), the outcome by its public codes, each registered feature's definition in words and
in code (a daily summary, an intraday phenotype's SQL, a defined phenotype's language, a proposed feature's
recipe), the covariates, the quality rules, the pre-registration (directions, the transforms, scales and
prediction models frozen on the discovery share: aggregates), the sealed holdout's results (masked), the
scorecard, the code version, and a methods protocol in words for an external cohort or for a later All of Us
release restricted to participants added since. The original holdout's results are for comparison only: an
external test is a fresh test, judged on its own.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import asdict
from pathlib import Path
from typing import Any

from codas.aou import cohort
from codas.aou.privacy import mask_small_counts, mask_small_counts_in_text

PLACEHOLDER_CDR = "your-project.your_cdr_dataset"


def package_dir(out: Path, stem: str) -> Path:
    return Path(out) / f"{stem}_replication"


def _feature_text(feature: str, spec: cohort.CohortSpec, state: dict[str, Any]) -> str:
    """One registered feature's definition in words."""
    from codas.aou.phenotypes import describe

    for d in state.get("defined_phenotypes") or []:
        if d.get("column") == feature:
            return f"defined on the day-by-day baseline: {d.get('description')}"
    for p in state.get("proposed_features") or []:
        if p.get("name") == feature:
            return f"{p.get('op')} of {p.get('a')} and {p.get('b')}"
    for source in spec.phenotypes:
        for column, text in describe(source):
            if column == feature:
                return f"{text} ({source.table}, over the baseline window)"
    for source in spec.wearables:
        for column in source.columns:
            if feature == f"{source.prefix}_{column}_mean":
                return f"mean of daily {column} ({source.table}) over the {spec.window_days}-day baseline window"
            if feature == f"{source.prefix}_{column}_sd":
                return f"day-to-day SD of daily {column} ({source.table}) over the {spec.window_days}-day baseline window"
    return feature


def _outcome_text(spec: cohort.CohortSpec) -> str:
    o = spec.outcome
    codes = ", ".join(o.codes) or ", ".join(f"OMOP concept {c}" for c in o.concept_ids)
    with_descendants = " and their descendants" if o.include_descendants else ""
    if o.kind == "condition":
        text = (f"a new diagnosis of {codes}{with_descendants}, in the condition records; a case needs diagnoses on "
                f"{o.min_occurrences} or more distinct dates and its event date is the first; a diagnosis before "
                f"follow-up starts makes the participant prevalent and leaves them out; follow-up runs from the "
                f"index date plus {spec.lag_days} days to the first diagnosis or the last EHR visit")
    else:
        from codas.aou.phenotypes import range_text

        bounds = range_text([o.value_min, o.value_max]) if (o.value_min, o.value_max) != (None, None) else ""
        text = (f"the first value of {codes}{with_descendants} measured from the index date plus {spec.lag_days} days"
                + (f" and before {spec.lag_days + spec.horizon_days} days" if spec.horizon_days else "")
                + (f", keeping values {bounds}" if bounds else ""))
    return text


def protocol(spec: cohort.CohortSpec, label: str, prereg: dict[str, Any], result: dict[str, Any] | None,
             state: dict[str, Any]) -> str:
    """The methods protocol, in words, for testing the registered hypotheses in another cohort."""
    from codas.aou.runner import _describe

    survival = bool(prereg.get("survival_time"))
    lines = [f"# Replication protocol: {label}", "",
             "Generated by CoDaS from the pre-registration of this outcome. It specifies the test in advance; the "
             "original holdout's results at the end are for comparison only and must not shape the analysis.", "",
             "## Population and time zero", "",
             f"Adults with at least {spec.min_wear_days} valid wear days in a baseline window of {spec.window_days} days "
             "that starts at their first valid wear day; the index date (time zero) is the end of that window.", ""]
    rules = cohort.quality_rules(spec)
    if rules:
        lines += ["Quality rules:", "", *[f"- {r}" for r in rules], ""]
    lines += ["## Outcome", "", _outcome_text(spec) + ".", "",
              "## Exposures (one per registered hypothesis)", "",
              "| feature | definition | predicted direction | registered magnitude | frozen scale |", "|---|---|---|---|---|"]
    for h in prereg.get("hypotheses") or []:
        magnitude = h.get("magnitude") or {}
        mag = (f"{magnitude.get('measure')} {magnitude.get('low')}-{magnitude.get('high')}" if magnitude else "-")
        scale = h.get("effect_scale") or {}
        transform = h.get("transform") or {}
        frozen = "; ".join(x for x in (
            f"SD {transform.get('scale'):.4g}" if isinstance(transform.get("scale"), (int, float)) else "",
            "logged" if transform.get("log") else "",
            f"natural unit {scale.get('unit')}" if scale.get("unit") is not None else "") if x) or "-"
        direction = "higher is worse" if h.get("direction", 0) > 0 else "higher is protective"
        if not survival:
            direction = "rises with the outcome" if h.get("direction", 0) > 0 else "falls as the outcome rises"
        lines.append(f"| {h['feature']} | {_feature_text(h['feature'], spec, state)} | {direction} | {mag} | {frozen} |")
    lines += ["", "Compare effects per SD of your own cohort and, for the scale to match, also per the frozen SD and per "
              "natural unit given here.", "", "## Covariates", ""]
    names = set(prereg.get("confounders") or [])
    for c in spec.covariates:
        if c.name in names:
            codes = ", ".join(getattr(c, "codes", None) or []) or ", ".join(map(str, c.concept_ids))
            lines.append(f"- {c.name}: {_describe(c)}" + (f" ({codes})" if codes else ""))
    other = sorted(names - {c.name for c in spec.covariates})
    if other:
        lines.append(f"- also: {', '.join(other)} (demographics and the days with wearable data in the window)")
    m = int(prereg.get("covariate_imputations") or 0)
    model = ("a Cox proportional-hazards model (Efron ties), the hazard ratio per SD of each exposure" if survival
             else "the partial Spearman correlation of each exposure with the outcome")
    lines += ["", "## Analysis", "",
              f"- {model}, adjusted for the covariates above"
              + (f"; missing covariate values multiply imputed ({m} imputations; for a time to event the imputation "
                 "model holds the event indicator and the Nelson-Aalen cumulative hazard), with the complete-case "
                 "estimate as a sensitivity analysis" if m else "") + ".",
              "- Effect sizes: per natural unit, by quarter of the exposure (on the cut-points given in the "
              "pre-registration) with a test for trend" + (", the cumulative incidence by quarter at "
                                                             f"{int(prereg.get('absolute_risk_horizon_days') or 0) // 365} years, "
                                                             "the E-value of the confidence bound"
                                                             if survival else "") + ", and the gain in "
              + ("Harrell's C" if survival else "R^2") + " of a model with the exposure over the covariates alone.",
              "- Falsification: a monotone dose-response across quantiles"
              + (f"; the effect with the first {prereg.get('sensitivity_lag_days')} days of follow-up left out"
                 if survival else "")
              + ("; no association with the negative-control outcomes " + ", ".join(prereg.get("negative_controls") or [])
                 if prereg.get("negative_controls") else "")
              + ("; the effect holds when the days with wearable data are added to the covariates"
                 if prereg.get("availability") else "")
              + ("; consistency across strata of " + ", ".join(prereg.get("heterogeneity") or [])
                 + " (Cochran's Q and I^2)" if prereg.get("heterogeneity") else "") + ".", "",
              "## Success criteria (fixed before the test)", "",
              "Each hypothesis replicates when its effect has the predicted direction and its 95% confidence interval "
              "excludes no effect, at a one-sided alpha of 0.05; with several hypotheses, judge them together by "
              "Benjamini-Hochberg at 0.05. The original holdout's online false-discovery-rate procedure does not carry "
              "over: an external cohort is a new, independent test. A later All of Us release qualifies only when "
              "restricted to participants who were in neither share of this one.", ""]
    rows = [r for r in (result or {}).get("hypotheses") or [] if "same_direction" in r]
    if rows:
        rungs = {r["feature"]: r["rung"] for r in (state.get("scorecard") or {}).get("hypotheses") or []}
        lines += ["## What the original sealed holdout showed (for comparison only)", "",
                  "| feature | effect (95% CI) | status | robust | evidence rung |", "|---|---|---|---|---|"]
        for r in rows:
            effect = r.get("hr_per_sd", r.get("rho"))
            ci = r.get("ci95") or ["", ""]
            lines.append(f"| {r['feature']} | {effect} ({ci[0]} to {ci[1]}) | {r.get('status', '')} | "
                         f"{'yes' if r.get('robust') else 'no'} | {rungs.get(r['feature'], '-')} |")
        lines.append("")
    return mask_small_counts_in_text("\n".join(lines) + "\n")


def write_package(out: Path, spec: cohort.CohortSpec, label: str, prereg: dict[str, Any], result: dict[str, Any] | None,
                  state: dict[str, Any], *, code_version: str, cdr: str) -> Path:
    """Write the package to ``<out>/<stem>_replication/`` and return that folder."""
    folder = package_dir(out, spec.name)
    folder.mkdir(parents=True, exist_ok=True)
    sql, params = cohort.build_cohort_sql(spec, PLACEHOLDER_CDR)
    blocks = [("extraction.sql", sql, params)]
    if spec.phenotypes and spec.design == "incident":
        blocks.append(("phenotypes.sql", *cohort.build_phenotype_sql(spec, PLACEHOLDER_CDR)))
    if spec.day_store is not None and spec.design == "incident":
        from codas.aou import daystore

        blocks.append(("day_store.sql", *daystore.build_daystore_sql(spec, PLACEHOLDER_CDR)))
    if spec.month_store is not None and spec.design == "incident":
        from codas.aou import monthstore

        blocks.append(("month_store.sql", *monthstore.build_monthstore_sql(spec, PLACEHOLDER_CDR)))
    files: dict[str, str] = {}
    for name, text, bound in blocks:
        files[name] = (f"-- {spec.name}: replace {PLACEHOLDER_CDR} with your CDR; parameters below are bound, not inlined\n"
                       + text + "\n\n" + "\n".join(f"-- @{n} {t} = {json.dumps(v, default=str)}" for n, t, v in bound) + "\n")
    defined = {d["column"]: d.get("definition") for d in state.get("defined_phenotypes") or []}
    proposed = {p["name"]: {k: p.get(k) for k in ("op", "a", "b")} for p in state.get("proposed_features") or []}
    features = {h["feature"]: {"definition": _feature_text(h["feature"], spec, state),
                               **({"phenotype": defined[h["feature"]]} if h["feature"] in defined else {}),
                               **({"recipe": proposed[h["feature"]]} if h["feature"] in proposed else {})}
                for h in prereg.get("hypotheses") or []}
    lock = cohort.ROOT / "scripts" / "aou" / "feature_definitions.json"
    record = {"cohort_spec.json": asdict(spec), "features.json": features,
              "pre_registration.json": mask_small_counts(prereg),
              "holdout_results.json": mask_small_counts(result or {}),
              "scorecard.json": mask_small_counts(state.get("scorecard") or {}),
              "feature_definition_hashes.json": json.loads(lock.read_text()) if lock.exists() else {}}
    for name, value in record.items():
        files[name] = json.dumps(value, indent=1, default=str) + "\n"
    files["protocol.md"] = protocol(spec, label, prereg, result, state)
    for name, text in files.items():
        (folder / name).write_text(text, encoding="utf-8")
    manifest = {"outcome": spec.name, "label": label, "code_version": code_version,
                "cdr_release": cdr.split(".")[-1], "pre_registration_sha256": prereg.get("sha256"),
                "files": {n: hashlib.sha256(t.encode()).hexdigest() for n, t in sorted(files.items())}}
    (folder / "MANIFEST.json").write_text(json.dumps(manifest, indent=1) + "\n", encoding="utf-8")
    return folder
